/*SELECT - TODOS OS DADOS AGRUPADOS*/
CREATE VIEW VW_TODOS_OS_DADOS AS
SELECT U.MATRICULA, U.NOME_USUARIO, O.NOME_OBJETO, L.NOME_LOCAL, OC.STATUS, OC.DATA_OCORRENCIA, U.TELEFONE
FROM OCORRENCIA OC
INNER JOIN USUARIO U
ON U.IDUSUARIO = OC.ID_USUARIO 
INNER JOIN LOCAL L 
ON L.IDLOCAL = OC.ID_LOCAL 
INNER JOIN OBJETO O 
ON O.IDOBJETO = OC.ID_OBJETO ;

SELECT * FROM VW_TODOS_OS_DADOS;

