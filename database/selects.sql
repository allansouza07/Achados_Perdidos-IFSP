/*SELECT - QUANTIDADE DE OCORRENCIAS DE TODOS OS LOCAIS*/
CREATE VIEW VW_QTD_LOCAIS AS
SELECT 
    L.NOME_LOCAL,
    COUNT(*) AS OCORRENCIAS
FROM LOCAL L
INNER JOIN OCORRENCIA OC
    ON L.IDLOCAL = OC.ID_LOCAL
GROUP BY L.IDLOCAL, L.NOME_LOCAL;

SELECT * FROM VW_QTD_LOCAIS;

/*SELECT - QUANTIDADE DE OCORRENCIAS DE UM DETERMINADO LOCAL*/
DELIMITER $
CREATE PROCEDURE VER_QTD_LOCAL(ID INT)
BEGIN
	SELECT 
	    L.NOME_LOCAL,
	    COUNT(*) AS OCORRENCIAS
	FROM LOCAL L
	INNER JOIN OCORRENCIA OC
	    ON L.IDLOCAL = OC.ID_LOCAL
	WHERE L.IDLOCAL = ID
	GROUP BY L.IDLOCAL, L.NOME_LOCAL;
END $
DELIMITER ;

CALL VER_QTD_LOCAL(x);

/*SELECT - QUANTIDADE DE OCORRENCIAS DE UMA PESSOA*/
DELIMITER $
CREATE PROCEDURE VER_QTD_PESSOA(ID INT)
BEGIN
	SELECT 
	    U.NOME_USUARIO,
	    COUNT(*) AS OCORRENCIAS
	FROM USUARIO U 
	INNER JOIN OCORRENCIA OC
	    ON U.IDUSUARIO = OC.ID_USUARIO
	WHERE U.IDUSUARIO = ID
	GROUP BY U.IDUSUARIO, U.NOME_USUARIO;
END $
DELIMITER ;

CALL VER_QTD_PESSOA(x);